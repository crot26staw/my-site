/**
 * Кейсы. Чтобы добавить работу — добавьте объект в массив.
 * Все кейсы — на странице /cases, на главной — первые HOME_CASES (порядок в массиве = порядок показа).
 * Цены в кейсах не показываем. url — внешняя ссылка на сайт (пока плейсхолдер).
 * Кейс со slug и details открывается подробно: модалка поверх страницы и свой адрес /cases/<slug>.
 * Картинки — в public/images/cases/<slug>/, путь от корня сайта: "/images/cases/<slug>/preview.png".
 */
export interface Case {
  title: string;
  task: string;
  result: string;
  image: string;
  url: string;
  /** Для кейсов редизайна: слайдер «до/после». Пути к изображениям или плейсхолдеры. */
  beforeAfter?: { before: string; after: string };
  /** Адрес подробной страницы: /cases/<slug>. Без slug карточка не открывается. */
  slug?: string;
  details?: CaseDetails;
}

export interface CaseDetails {
  client: string;
  /** Что делали — метки под заголовком. */
  tags: string[];
  /** Цифры проекта: значение и подпись. */
  facts: { value: string; label: string }[];
  /** Задача подробно — абзацы. */
  task: string[];
  done: string[];
  /** Результат подробно — абзацы. */
  result: string[];
  /** Полный скриншот сайта и его размер в пикселях (чтобы место под него было занято до загрузки). */
  screenshot: { src: string; width: number; height: number };
}

