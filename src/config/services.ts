/**
 * Услуги. Коротко (audience, items) — на главной, с тем, что входит, и ценой — на странице /services,
 * полностью — на странице услуги /services/<id>. id — и адрес страницы, и якорь на /services.
 */
export interface Service {
  id: string;
  title: string;
  audience: string;
  items: { name: string; text: string }[];
  /** Что входит в работу — только на странице /services. */
  includes: string[];
  price: string;

  /* Страница услуги /services/<id> */
  /** Подзаголовок: что это за услуга в двух предложениях. */
  summary: string;
  /** Что это даёт бизнесу. */
  benefits: { title: string; text: string }[];
  /** Когда нужна услуга — признаки, по которым клиент узнаёт свою ситуацию. */
  signs: string[];
  /** Как проходит работа, по шагам. */
  process: { title: string; text: string }[];
  /** Вопросы именно про эту услугу. */
  faq: { q: string; a: string }[];

  /**
   * Кнопка: lead — открыть модалку заявки с этой формой, иначе — переход к блоку главной section.
   */
  cta: { label: string; section: "quiz" | "contact"; lead?: "new" | "audit" };
}

